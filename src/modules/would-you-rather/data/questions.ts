/**
 * 获取正式审核通过的可玩题目集合
 * 依据 P0-2：只有 reviewStatus === "approved" 才能进入公开游玩与投票
 */
export function getPlayableQuestions(
  questions: readonly Question[] = QUESTIONS_DATABASE,
): readonly Question[] {
  return questions.filter((q) => q.reviewStatus === "approved");
}

/**
 * 获取指定专题的正式审核通过题目
 * 依据 P0-2：不同专题必须同时满足审核通过及对应维度的适用性约束
 */
export function getPlayableQuestionsByCollection(
  collectionKey: FeaturedCollectionKey,
  questions: readonly Question[] = QUESTIONS_DATABASE,
): readonly Question[] {
  return questions.filter((q) => {
    if (q.reviewStatus !== "approved") return false;
    switch (collectionKey) {
      case "kids":
        return q.suitability.kids === "suitable" && q.ageGroups.length > 0;
      case "funny":
        return q.tones.includes("funny");
      case "hard":
        return q.difficulty === "hard";
      case "friends":
        return q.relationships.includes("friends");
      case "couples":
        return q.relationships.includes("couples");
      default:
        return false;
    }
  });
}

/**
 * 专题题集入口 (默认返回经过严格审核的可玩题目)
 */
export function getQuestionsByCollection(
  collectionKey: FeaturedCollectionKey,
  questions: readonly Question[] = QUESTIONS_DATABASE,
): readonly Question[] {
  return getPlayableQuestionsByCollection(collectionKey, questions);
}

/**
 * 首页可玩题目精选
 */
export function getHomepageQuestions(
  count = 50,
  questions: readonly Question[] = QUESTIONS_DATABASE,
): readonly Question[] {
  return getPlayableQuestions(questions).slice(0, count);
}
